    suspend fun getResponse(userMessage: String, @Suppress("UNUSED_PARAMETER") history: List<ChatMessage>): String {
        return withContext(Dispatchers.Default) {
            val lowerMessage = userMessage.lowercase().trim()

            when {
                // Привітання
                containsAny(lowerMessage, listOf("привіт", "хай", "хей", "доброго", "добрий", "здоров", "куку", "hello", "hi", "hey")) ->
                    greetings.random()

                // Як справи
                containsAny(lowerMessage, listOf("як справи", "як ти", "як життя", "як ся маєш", "ти як", "що чути", "як воно")) ->
                    howAreYou.random()

                // Прощання
                containsAny(lowerMessage, listOf("бувай", "до побачення", "папа", "бува", "на все добре", "прощавай", "bye", "goodbye", "до зустрічі")) ->
                    goodBye.random()

                // Подяка
                containsAny(lowerMessage, listOf("дякую", "спасибі", "thanks", "thank", "дуже вдячний", "вдячна")) ->
                    thanks.random()

                // Ім'я
                containsAny(lowerMessage, listOf("як тебе звати", "хто ти", "твоє ім'я", "як тебе звуть", "представся")) ->
                    nameQuestions.random()

                // Вік
                containsAny(lowerMessage, listOf("скільки тобі років", "який твій вік", "коли ти народилася", "ти стара", "ти молода")) ->
                    ageQuestions.random()

                // Погода
                containsAny(lowerMessage, listOf("погода", "яка погода", "дощ", "сніг", "сонце", "тепло", "холодно")) ->
                    weatherQuestions.random()

                // Любов
                containsAny(lowerMessage, listOf("люблю", "кохаю", "ти мене любиш", "любов")) ->
                    loveQuestions.random()

                // Жарти
                containsAny(lowerMessage, listOf("жарт", "анекдот", "розсміши", "смішне", "посміятися", "гумор", "прикол")) ->
                    jokeList.random()

                // Допомога
                containsAny(lowerMessage, listOf("що ти вмієш", "допоможи", "що можеш", "допомога", "функції", "команди")) ->
                    helpResponses.random()

                // Сум
                containsAny(lowerMessage, listOf("сумно", "погано", "журба", "депресія", "плачу", "гірко", "невесело")) ->
                    sadResponses.random()

                // Радість
                containsAny(lowerMessage, listOf("щасливий", "радий", "чудово", "супер", "класно", "круто", "прекрасно", "чудовий")) ->
                    happyResponses.random()

                // Їжа
                containsAny(lowerMessage, listOf("їжа", "смачно", "поїсти", "обід", "вечеря", "сніданок", "голодний", "кава", "чай")) ->
                    foodResponses.random()

                // Робота
                containsAny(lowerMessage, listOf("робота", "працюю", "працювати", "офіс", "зарплата", "бізнес")) ->
                    workResponses.random()

                // Навчання
                containsAny(lowerMessage, listOf("навчання", "школа", "університет", "студент", "вчуся", "уроки", "екзамен")) ->
                    studyResponses.random()

                // Музика
                containsAny(lowerMessage, listOf("музика", "пісня", "співати", "мелодія", "трек", "альбом")) ->
                    musicResponses.random()

                // Ігри
                containsAny(lowerMessage, listOf("гра", "ігри", "геймінг", "пограти", "геймер")) ->
                    gameResponses.random()

                // Час
                containsAny(lowerMessage, listOf("котра година", "який час", "скільки часу")) ->
                    timeResponses.random()

                // Emerald
                containsAny(lowerMessage, listOf("емеральд", "emerald", "смарагд", "додаток")) ->
                    emeraldResponses.random()

                // Творець
                containsAny(lowerMessage, listOf("хто тебе створив", "твій творець", "хто зробив", "розробник", "fedir", "федір")) ->
                    creatorResponses.random()

                // Цікаві факти
                containsAny(lowerMessage, listOf("цікавий факт", "факт", "цікавинка", "дивовижний", "неймовірний")) ->
                    randomFacts.random()

                // Питання про користувача
                containsAny(lowerMessage, listOf("а тебе", "а ти", "твоя улюблена", "твій улюблений")) ->
                    listOf(
                        "Моє улюблене — це спілкуватися з тобою!",
                        "Я люблю все, що пов'язане з допомогою людям!",
                        "Моя улюблена справа — це розмови з користувачами!"
                    ).random()

                // Так/ні питання
                lowerMessage.contains("?") && containsAny(lowerMessage, listOf("так", "ні", "чи")) ->
                    listOf(
                        "Цікаве питання! Я думаю, що так!",
                        "Хм, я схиляюся до того, що ні.",
                        "Важко сказати напевно, але мені здається, що так!",
                        "Я не впевнена, але, можливо!"
                    ).random()

                // Короткі відповіді (так/ні/ок)
                lowerMessage in listOf("так", "да", "yes", "ok", "ок", "ага", "угу") ->
                    listOf(
                        "Чудово!",
                        "Супер!",
                        "Домовилися!",
                        "Класно!"
                    ).random()

                lowerMessage in listOf("ні", "no", "не", "ноу") ->
                    listOf(
                        "Шкода!",
                        "Може, передумаєш?",
                        "Як скажеш!",
                        "Зрозуміло!"
                    ).random()

                // Якщо нічого не підійшло — випадкова відповідь
                else -> unknownResponses.random()
            }
        }
    }

    private fun containsAny(text: String, keywords: List<String>): Boolean {
        return keywords.any { text.contains(it) }
    }
